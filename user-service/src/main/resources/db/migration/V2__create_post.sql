-- One user has many posts: the foreign key lives on the "many" side (post.user_id).

CREATE TABLE post (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(500) NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    user_id     INTEGER      NOT NULL,
    CONSTRAINT fk_post_user FOREIGN KEY (user_id) REFERENCES user_details (id)
);

-- Most queries are "posts of user X": index the foreign key
CREATE INDEX idx_post_user_id ON post (user_id);
